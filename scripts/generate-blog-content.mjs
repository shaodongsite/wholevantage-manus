import fs from 'node:fs'
import path from 'node:path'
import matter from 'gray-matter'

const projectRoot = process.cwd()
const blogDir = path.join(projectRoot, 'content', 'blog')
const outputPath = path.join(projectRoot, 'lib', 'blog-content.generated.ts')

const posts = fs
  .readdirSync(blogDir)
  .filter((fileName) => /\.mdx?$/.test(fileName))
  .sort()
  .map((fileName) => {
    const raw = fs.readFileSync(path.join(blogDir, fileName), 'utf8')
    const { data, content } = matter(raw)
    return {
      fileName,
      slug: data.slug || fileName.replace(/\.mdx?$/, ''),
      title: data.title,
      subtitle: data.subtitle ?? null,
      date: data.date,
      lang: data.lang,
      excerpt: data.excerpt,
      author: data.author,
      category: data.category ?? null,
      tags: data.tags ?? null,
      content,
    }
  })

const source = `// This file is generated by scripts/generate-blog-content.mjs.\n// Do not edit it manually.\n\nexport const generatedBlogPosts = ${JSON.stringify(posts, null, 2)} as const\n`
fs.writeFileSync(outputPath, source)
console.log(`Generated ${posts.length} blog posts at ${path.relative(projectRoot, outputPath)}`)
